// Scans public/sounds/ for available sound variants and writes src/lib/sound-manifest.js.
// Regenerate with: pnpm run sounds:manifest
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// Re-exported so consumers (and this file's own tests) have a single source
// of truth shared with the browser bundle at src/lib/pick-variant.js.
export { pickVariant } from '../src/lib/pick-variant.js'

const keyForRelativePath = relativePath => {
    const breakFlat = relativePath.match(/^overtime\/break\/(\d+)\.webm$/)
    if (breakFlat) return `overtime_break_${parseInt(breakFlat[1], 10)}`

    const breakDir = relativePath.match(/^overtime\/break\/(\d+)\/.+\.webm$/)
    if (breakDir) return `overtime_break_${parseInt(breakDir[1], 10)}`

    const flat = relativePath.match(/^(elapsed|remaining|overtime)\/(\d+)\.webm$/)
    if (flat) return `${flat[1]}_${parseInt(flat[2], 10)}`

    const dir = relativePath.match(/^(elapsed|remaining|overtime)\/(\d+)\/.+\.webm$/)
    if (dir) return `${dir[1]}_${parseInt(dir[2], 10)}`

    const timesupFlat = relativePath.match(/^timesup\/([a-zA-Z-]+)\.webm$/)
    if (timesupFlat) return `timesup_${timesupFlat[1]}`

    const timesupDir = relativePath.match(/^timesup\/([a-zA-Z-]+)\/.+\.webm$/)
    if (timesupDir) return `timesup_${timesupDir[1]}`

    const notification = relativePath.match(/^notifications\/(\d+)\.ogg$/)
    if (notification) return `notification_${parseInt(notification[1], 10)}`

    if (relativePath === 'button.webm') return 'button'
    if (relativePath === 'timer-end.webm') return 'timerFinished'

    return null
}

const walk = dir => {
    const entries = fs.readdirSync(dir, { withFileTypes: true })
    const files = []
    for (const entry of entries) {
        const full = path.join(dir, entry.name)
        if (entry.isDirectory()) {
            files.push(...walk(full))
        } else if (entry.isFile()) {
            files.push(full)
        }
    }
    return files
}

// Scans `root` (a sounds directory, e.g. public/sounds) and returns
// { [manifestKey]: [absoluteUrl, ...] }, values sorted for stable output.
export const scanSoundManifest = root => {
    const manifest = {}

    if (!fs.existsSync(root)) return manifest

    for (const absolutePath of walk(root)) {
        const relativePath = path.relative(root, absolutePath).split(path.sep).join('/')
        const key = keyForRelativePath(relativePath)
        if (!key) continue

        const url = `/tymer/sounds/${relativePath}`
        if (!manifest[key]) manifest[key] = []
        manifest[key].push(url)
    }

    for (const key of Object.keys(manifest)) {
        manifest[key].sort()
    }

    return manifest
}

const generateManifestSource = manifest => {
    const lines = Object.keys(manifest)
        .sort()
        .map(key => `    ${key}: ${JSON.stringify(manifest[key])},`)
        .join('\n')

    return `// AUTO-GENERATED by build-tools/generate-sound-manifest.js — do not edit by hand.
// Regenerate: pnpm run sounds:manifest
export const SOUND_VARIANTS = {
${lines}
}
`
}

const isMain = () => {
    if (!process.argv[1]) return false
    return fileURLToPath(import.meta.url) === path.resolve(process.argv[1])
}

if (isMain()) {
    const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
    const soundsRoot = path.join(repoRoot, 'public', 'sounds')
    const manifest = scanSoundManifest(soundsRoot)
    const outputPath = path.join(repoRoot, 'src', 'lib', 'sound-manifest.js')

    fs.writeFileSync(outputPath, generateManifestSource(manifest))
    console.log(`Wrote ${Object.keys(manifest).length} sound keys to ${outputPath}`)
}
