// Scans public/sounds/ for available sound variants and writes src/lib/sound-manifest.ts.
// Regenerate with: pnpm run sounds:manifest
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// Re-exported so consumers (and this file's own tests) have a single source
// of truth shared with the browser bundle at src/lib/pick-variant.ts.
export { pickVariant } from '../src/lib/pick-variant.ts'

// Strips a trailing `-<digits>` take suffix from a filename stem, e.g.
// `brisk-1` -> `brisk`. Used to derive the set name for files inside an
// event take-directory.
const setForStem = stem => stem.replace(/-\d+$/, '')

const setForTakePath = relativePath => {
    const stem = path.basename(relativePath, path.extname(relativePath))
    return setForStem(stem)
}

// Returns { key, set } for a matched relative path, or null when unmatched.
// `set` is the take's voice/character name for files inside an event
// take-directory, null for every set-less file (flat layouts, notifications,
// button, timer-end) — those belong to every set.
const keyForRelativePath = relativePath => {
    const breakFlat = relativePath.match(/^(elapsed|remaining|overtime)\/break\/(\d+)\.webm$/)
    if (breakFlat) return { key: `${breakFlat[1]}_break_${parseInt(breakFlat[2], 10)}`, set: null }

    const breakDir = relativePath.match(/^(elapsed|remaining|overtime)\/break\/(\d+)\/.+\.webm$/)
    if (breakDir)
        return {
            key: `${breakDir[1]}_break_${parseInt(breakDir[2], 10)}`,
            set: setForTakePath(relativePath),
        }

    const deadlineDir = relativePath.match(/^deadline\/(\d+)\/.+\.webm$/)
    if (deadlineDir)
        return {
            key: `deadline_${parseInt(deadlineDir[1], 10)}`,
            set: setForTakePath(relativePath),
        }

    const flat = relativePath.match(/^(elapsed|remaining|overtime)\/(\d+)\.webm$/)
    if (flat) return { key: `${flat[1]}_${parseInt(flat[2], 10)}`, set: null }

    const dir = relativePath.match(/^(elapsed|remaining|overtime)\/(\d+)\/.+\.webm$/)
    if (dir)
        return {
            key: `${dir[1]}_${parseInt(dir[2], 10)}`,
            set: setForTakePath(relativePath),
        }

    const timesupFlat = relativePath.match(/^timesup\/([a-zA-Z-]+)\.webm$/)
    if (timesupFlat) return { key: `timesup_${timesupFlat[1]}`, set: null }

    const timesupDir = relativePath.match(/^timesup\/([a-zA-Z-]+)\/.+\.webm$/)
    if (timesupDir) return { key: `timesup_${timesupDir[1]}`, set: setForTakePath(relativePath) }

    const notification = relativePath.match(/^notifications\/(\d+)\.ogg$/)
    if (notification) return { key: `notification_${parseInt(notification[1], 10)}`, set: null }

    if (relativePath === 'button.webm') return { key: 'button', set: null }
    if (relativePath === 'timer-end.webm') return { key: 'timerFinished', set: null }

    return null
}

const walk = dir => {
    const entries = fs.readdirSync(dir, { withFileTypes: true })
    const files = []
    for (const entry of entries) {
        const full = path.join(dir, entry.name)
        if (entry.isDirectory()) {
            files.push(...walk(full))
        } else if (entry.isFile()) {
            files.push(full)
        }
    }
    return files
}

// Scans `root` (a sounds directory, e.g. public/sounds) and returns
// { variants, sets }:
//  - variants: { [manifestKey]: [{ src, set }, ...] }, sorted by src for
//    stable output.
//  - sets: sorted array of the distinct non-null set names found.
export const scanSoundManifest = root => {
    const variants = {}
    const setsSeen = new Set()

    if (!fs.existsSync(root)) return { variants, sets: [] }

    for (const absolutePath of walk(root)) {
        const relativePath = path.relative(root, absolutePath).split(path.sep).join('/')
        const match = keyForRelativePath(relativePath)
        if (!match) continue

        const { key, set } = match
        const src = `/tymer/sounds/${relativePath}`
        if (!variants[key]) variants[key] = []
        variants[key].push({ src, set })
        if (set !== null) setsSeen.add(set)
    }

    for (const key of Object.keys(variants)) {
        variants[key].sort((a, b) => (a.src < b.src ? -1 : a.src > b.src ? 1 : 0))
    }

    return { variants, sets: [...setsSeen].sort() }
}

const generateManifestSource = ({ variants, sets }) => {
    const lines = Object.keys(variants)
        .sort()
        .map(key => `    ${key}: ${JSON.stringify(variants[key])},`)
        .join('\n')

    return `// AUTO-GENERATED by build-tools/generate-sound-manifest.js — do not edit by hand.
// Regenerate: pnpm run sounds:manifest
export type SoundVariant = { src: string; set: string | null }
export const SOUND_SETS: string[] = ${JSON.stringify(sets)}
export const SOUND_VARIANTS: Record<string, SoundVariant[]> = {
${lines}
}
`
}

const isMain = () => {
    if (!process.argv[1]) return false
    return fileURLToPath(import.meta.url) === path.resolve(process.argv[1])
}

if (isMain()) {
    const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
    const soundsRoot = path.join(repoRoot, 'public', 'sounds')
    const manifest = scanSoundManifest(soundsRoot)
    const outputPath = path.join(repoRoot, 'src', 'lib', 'sound-manifest.ts')

    fs.writeFileSync(outputPath, generateManifestSource(manifest))
    console.log(
        `Wrote ${Object.keys(manifest.variants).length} sound keys and ${manifest.sets.length} sets to ${outputPath}`,
    )
}
